"""Store of tested potentials: everything needed to find, cite and run one later.

Once a potential's tests finish, ``summarize-pot`` builds
``<run_dir>/<pot_name>/<pot_name>.json`` and — when the project's root
``settings.json`` has ``potinfo_savepath`` set (see
``gz_toolkit.potential_testing.settings``) — ``save_potinfo`` writes::

    <base>/pot_infobank/<pot_name>/        # e.g. gao_FeHe_2011/
        pot_info.json    # type_map, masses, lc, thermal_lc, pot_lines, reference, ...
        <potential files> # copied from potentials/<pot_name>/
        pot.inc          # LAMMPS pair_style / pair_coeff / mass lines
        README.md        # paper + DOI (+ GitHub / Matbench for universal pots), usage

``pot.inc`` assumes the potential files sit in the same directory as the
LAMMPS input; use it with ``include pot.inc`` after the box exists.

Reading back::

    pot = gz_toolkit.pot_infobank.load_tag("gao_FeHe_2011", infobank_dir="/path/to/pot_infobank")
    pot = gz_toolkit.pot_infobank.load_tag("gao2011", infobank_dir=...)  # short name also works
    lc_fe = get_lc(pot, "Fe")
    lc_fe9cr = get_lc(pot, "Fe", solute="Cr", at_pct=9)  # nearest tested composition
    pot_dir(...)  # folder holding the files, to copy next to an input

Overriding a looked-up value (e.g. in ``buildmtx``) needs no mechanism here
— callers should just accept an explicit ``lc=`` argument that short-circuits
the ``get_lc``/pot_infobank lookup entirely when given.
"""

from __future__ import annotations

import json
import re
import shutil
from functools import lru_cache
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from gz_toolkit.potential_testing.config import PotentialConfig

POT_INFO_FILENAME = "pot_info.json"
POT_INC_FILENAME = "pot.inc"
README_FILENAME = "README.md"
_TODO = "TODO (missing - add potential.reference in pot_inputs/<pot>.json and re-run summarize-pot)"


def render_pot_inc(record: dict) -> str:
    """LAMMPS include: pair lines + masses; potential files assumed next to the input."""
    type_map = record.get("type_map") or {}
    by_type = {int(t): el for el, t in type_map.items()}
    lines = [
        f"# {record.get('pot_name', '')} - generated by gz_toolkit.pot_infobank",
        "# Potential files are assumed to be in the same directory as the LAMMPS input.",
        "# Use after the simulation box exists:  include pot.inc",
        "# Type map: " + ", ".join(f"{t}={el}" for t, el in sorted(by_type.items())),
        "",
    ]
    lines += [ln.rstrip() for ln in str(record.get("pot_lines", "")).splitlines() if ln.strip()]
    masses = record.get("masses") or {}
    if masses:
        lines.append("")
        for t in sorted(masses, key=lambda k: int(k)):
            el = by_type.get(int(t), "")
            lines.append(f"mass            {int(t)} {float(masses[t]):g}" + (f"   # {el}" if el else ""))
    return "\n".join(lines) + "\n"


def _link(value: str, kind: str) -> str:
    v = value.strip()
    if kind == "doi" and not v.lower().startswith("http"):
        return f"[{v}](https://doi.org/{v})"
    if v.lower().startswith("http"):
        return f"<{v}>"
    return v


def render_readme(record: dict, missing: list[str]) -> str:
    """README.md: what the potential is, where it comes from, how to use it."""
    ref = record.get("reference") or {}
    name = record.get("pot_name", "")
    kind = record.get("kind", "classical")
    elements = [el for el, _ in sorted((record.get("type_map") or {}).items(), key=lambda kv: kv[1])]
    out = [f"# {name}", ""]
    out.append(f"- **Elements:** {', '.join(elements)}")
    out.append(f"- **Kind:** {kind}")
    out.append(f"- **Tested / saved:** {record.get('updated', '')}")
    out += ["", "## Reference", ""]
    keys = ["paper", "authors", "doi"] + (["github", "matbench"] if kind == "universal" else [])
    labels = {"paper": "Paper", "authors": "Authors", "doi": "DOI",
              "github": "GitHub", "matbench": "Matbench Discovery"}
    for k in keys:
        val = str(ref.get(k) or "").strip()
        if not val and k == "authors":
            continue
        out.append(f"- **{labels[k]}:** {_link(val, k) if val else _TODO}")
    for k, val in ref.items():
        if k not in labels and str(val).strip():
            out.append(f"- **{k}:** {val}")
    if missing:
        out += ["", f"> Missing information: {', '.join(missing)}."]

    files = record.get("potential_files") or []
    out += ["", "## Use in LAMMPS", ""]
    if files:
        out.append("Copy these files next to your LAMMPS input: " + ", ".join(f"`{f}`" for f in files) + ".")
    out += [
        "Then either `include pot.inc` (after `read_data`/`create_box`), or paste:",
        "",
        "```",
        *[ln.rstrip() for ln in str(record.get("pot_lines", "")).splitlines() if ln.strip()],
        "```",
        "",
        "`pot.inc` also sets the masses. Edit it if your type order differs from the type map above.",
    ]

    lc = record.get("lc") or {}
    pure = {k: v for k, v in lc.items() if k != "alloys"}
    if pure or lc.get("alloys"):
        out += ["", "## Lattice constants at 0 K (from the tests)", "", "| System | a (Å) |", "|---|---|"]
        for el, a in pure.items():
            struct = (record.get("crystal_structures") or {}).get(el, {}).get("structure", "")
            out.append(f"| {el}{f' ({struct})' if struct else ''} | {a:.4f} |")
        for pair, comps in (lc.get("alloys") or {}).items():
            for comp, a in comps.items():
                out.append(f"| {comp} | {a:.4f} |")
    out += ["", f"Full data: `{POT_INFO_FILENAME}`.", ""]
    return "\n".join(out)


def save_potinfo(cfg: "PotentialConfig", run_dir: str | Path = ".",
                 infobank_dir: str | Path | None = None) -> Path | None:
    """Write this potential's folder into the pot_infobank. Returns that folder, or None.

    ``infobank_dir`` defaults to what ``potinfo_savepath`` in ``<run_dir>/settings.json``
    resolves to; ``None`` there (saving off) makes this a no-op.
    Needs ``<run_dir>/<pot_name>/<pot_name>.json`` (run ``build_pot_tag_json`` first).
    """
    from gz_toolkit.potential_testing.config import missing_reference_fields
    from gz_toolkit.potential_testing.settings import resolve_infobank_dir

    root = Path(run_dir).resolve()
    if infobank_dir is None:
        infobank_dir = resolve_infobank_dir(root)
        if infobank_dir is None:
            return None
    name = cfg.potential.pot_name
    tag_json_path = root / name / f"{name}.json"
    if not tag_json_path.is_file():
        raise FileNotFoundError(
            f"No {name}.json at {tag_json_path} — run build_pot_tag_json() for this pot first."
        )
    record = json.loads(tag_json_path.read_text(encoding="utf-8"))
    missing = missing_reference_fields(cfg.potential)
    record["missing_info"] = missing
    record["source_project"] = str(root)

    dest = Path(infobank_dir) / name
    dest.mkdir(parents=True, exist_ok=True)
    src_dir = root / "potentials" / name
    for fname in cfg.potential.potential_files:
        src = src_dir / fname
        if src.is_file():
            target = dest / fname
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, target)
        else:
            missing.append(f"potential file {fname}")
    (dest / POT_INFO_FILENAME).write_text(json.dumps(record, indent=2), encoding="utf-8")
    (dest / POT_INC_FILENAME).write_text(render_pot_inc(record), encoding="utf-8")
    (dest / README_FILENAME).write_text(render_readme(record, missing), encoding="utf-8")
    _load_cached.cache_clear()
    if missing:
        print(f"[pot_infobank] {name}: missing {', '.join(missing)} — marked TODO in {dest / README_FILENAME}")
    return dest


