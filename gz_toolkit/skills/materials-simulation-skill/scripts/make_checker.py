#!/usr/bin/env python3
"""
make_checker.py — write a checker in the simulation ROOT from sim_plan `checks:`.

    python workflow/make_checker.py --lang py   # -> ROOT/checker.py  (uses workflow/checklib.py)
    python workflow/make_checker.py --lang sh   # -> ROOT/checker.sh  (pure bash, no Python needed)

Then the user runs, from ROOT:
    ./checker.sh                 or  python checker.py
    ./checker.sh -u              or  python checker.py -u        # list only unfinished runs
                                     python checker.py --by 2    # tally per level-2 directory
Both print one line per run dir (FINISHED / UNFINISHED / NOT_STARTED + reason) and a total,
and write status.csv.
"""
import argparse
import shlex
import stat
from pathlib import Path

from simflow_common import find_root, load_plan

PY_TEMPLATE = '''#!/usr/bin/env python3
"""Completion checker for this simulation tree (generated by make_checker.py).
Usage:  python checker.py [-u|--unfinished] [--by LEVEL]
Checks (edit sim_plan `checks:` and regenerate, or edit CHECKS below):
{doc}
"""
import argparse, csv, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "workflow"))
from checklib import status  # noqa: E402

CHECKS = {checks!r}

ap = argparse.ArgumentParser()
ap.add_argument("-u", "--unfinished", action="store_true", help="print only runs that are not FINISHED")
ap.add_argument("--by", type=int, default=None, help="tally per directory at this level")
a = ap.parse_args()

rows = list(csv.DictReader(open(ROOT / "manifest.csv", newline="")))
tally, groups, out = Counter(), {{}}, []
for r in rows:
    st, why = status(ROOT / r["relpath"], CHECKS)
    tally[st] += 1
    out.append((r["relpath"], st, "; ".join(why)))
    if a.by is not None:
        key = "/".join(Path(r["relpath"]).parts[:a.by]) or "."
        groups.setdefault(key, Counter())[st] += 1
    if not a.unfinished or st != "FINISHED":
        print(f"{{st:12s}} {{r['relpath']}}" + (f"   <- {{out[-1][2]}}" if why and st != "NOT_STARTED" else ""))
with open(ROOT / "status.csv", "w", newline="") as fh:
    w = csv.writer(fh); w.writerow(["relpath", "status", "reason"]); w.writerows(out)
if a.by is not None:
    print(f"\\n--- per level-{{a.by}} directory ---")
    for k, c in groups.items():
        print(f"{{k:40s}} " + "  ".join(f"{{s}}={{n}}" for s, n in sorted(c.items())))
print("\\nTOTAL " + "  ".join(f"{{s}}={{n}}" for s, n in sorted(tally.items())) + f"  (of {{len(rows)}})")
'''


def sh_test(c: dict) -> tuple[str, str]:
    """bash condition that is TRUE when the check passes, plus a failure reason."""
    f = c["file"]
    t = c["type"]
    first = f'$(ls -1d {f} 2>/dev/null | tail -n 1)'
    if t == "exists":
        return f'compgen -G "{f}" > /dev/null', f"{f} not found"
    if t == "missing":
        return f'! compgen -G "{f}" > /dev/null', f"{f} should not exist"
    if t == "count":
        return f'[ "$(ls -1d {f} 2>/dev/null | wc -l)" -ge {int(c.get("min", 1))} ]', f"fewer than {c.get('min', 1)} x {f}"
    if t == "min_lines":
        return f'[ -n "{first}" ] && [ "$(wc -l < "{first}")" -ge {int(c["n"])} ]', f"{f} < {c['n']} lines"
    if t == "min_size":
        return f'[ -n "{first}" ] && [ "$(wc -c < "{first}")" -ge {int(c["bytes"])} ]', f"{f} < {c['bytes']} bytes"
    p = shlex.quote(c["pattern"])
    if t == "contains":
        return f'[ -n "{first}" ] && grep -Eq {p} "{first}"', f"{f} lacks /{c['pattern']}/"
    if t == "not_contains":
        return f'[ -n "{first}" ] && ! grep -Eq {p} "{first}"', f"{f} contains /{c['pattern']}/"
    if t == "last_line":
        return (f'[ -n "{first}" ] && grep -v "^[[:space:]]*$" "{first}" | tail -n 1 | grep -Eq {p}',
                f"{f} last line lacks /{c['pattern']}/")
    raise SystemExit(f"unknown check type {t}")


def make_sh(checks: list[dict]) -> str:
    files = sorted({c["file"] for c in checks if c["type"] != "missing"})
    tests = []
    for c in checks:
        cond, why = sh_test(c)
        tests.append(f'    if ! ( {cond} ); then reasons="$reasons; {why}"; fi')
    touched = " || ".join(f'compgen -G "{f}" > /dev/null' for f in files) or "false"
    return f'''#!/usr/bin/env bash
# Completion checker for this simulation tree (generated by make_checker.py).
# Usage: ./checker.sh [-u]     (-u: print only runs that are not FINISHED)
# Reads run dirs from manifest.csv (first column). Writes status.csv.
ROOT="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
ONLY_UNFINISHED=0; [ "$1" = "-u" ] && ONLY_UNFINISHED=1
fin=0; unf=0; nst=0; total=0
echo "relpath,status,reason" > "$ROOT/status.csv"
while IFS=, read -r rel _rest; do
  [ "$rel" = "relpath" ] && continue
  total=$((total+1))
  cd "$ROOT/$rel" 2>/dev/null || {{ echo "MISSING_DIR  $rel"; continue; }}
  reasons=""
{chr(10).join(tests)}
  if [ -z "$reasons" ]; then st=FINISHED; fin=$((fin+1))
  elif {touched}; then st=UNFINISHED; unf=$((unf+1))
  else st=NOT_STARTED; nst=$((nst+1)); fi
  reasons="${{reasons#; }}"
  echo "$rel,$st,\\"$reasons\\"" >> "$ROOT/status.csv"
  if [ $ONLY_UNFINISHED -eq 0 ] || [ $st != FINISHED ]; then
    if [ $st = UNFINISHED ]; then printf "%-12s %s   <- %s\\n" $st "$rel" "$reasons"
    else printf "%-12s %s\\n" $st "$rel"; fi
  fi
done < "$ROOT/manifest.csv"
echo
echo "TOTAL FINISHED=$fin  UNFINISHED=$unf  NOT_STARTED=$nst  (of $total)"
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root")
    ap.add_argument("--lang", choices=["py", "sh"], default="sh")
    a = ap.parse_args()
    root = find_root(a.root)
    checks = load_plan(root).get("checks") or []
    if not checks:
        raise SystemExit("[simflow] sim_plan has no `checks:` — ask the user for the completion criteria first")
    if a.lang == "py":
        doc = "\n".join(f"  - {c}" for c in checks)
        out = root / "checker.py"
        text = PY_TEMPLATE.format(checks=checks, doc=doc)
    else:
        out = root / "checker.sh"
        text = make_sh(checks)
    with out.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    out.chmod(out.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP)
    print(f"[simflow] wrote {out}")


if __name__ == "__main__":
    main()
